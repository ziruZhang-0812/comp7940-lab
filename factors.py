# ===================== 练习 1：找出一个数的所有因数 =====================
x = 52633
print(f"练习1 - 数字 {x} 的所有因数：")
for i in range(2, x):
    # % 是取余运算符，余数为0说明i是x的因数
    if x % i == 0:
        print(i, end=" ")
print("\n" + "="*50)

# ===================== 练习 2：封装为函数 =====================
def print_factor(x):
    """
    函数功能：打印输入数字x的所有因数
    参数x：需要查找因数的整数
    """
    print(f"练习2 - 数字 {x} 的所有因数：")
    # 处理边界情况：x小于2时无因数
    if x < 2:
        print("无因数（数字小于2）")
        return
    # 遍历查找因数
    factors = []  # 用列表存储因数，方便输出
    for i in range(2, x):
        if x % i == 0:
            factors.append(i)
    # 输出结果
    if factors:
        print(factors)
    else:
        print(f"{x} 是质数（无除1和自身外的因数）")

# 测试函数（用x=52633）
print_factor(52633)
print("="*50)

# ===================== 练习 3：遍历列表调用函数 =====================
l = [52633, 8137, 1024, 999]
print("练习3 - 列表中每个数字的因数：")
for num in l:
    print_factor(num)
    print("-"*30)  # 分隔线，方便查看# Python文件注释
